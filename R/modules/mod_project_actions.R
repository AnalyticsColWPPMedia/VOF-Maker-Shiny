# R/modules/mod_project_actions.R
# Project-level actions over the VOF Metadata history: restore from code,
# legacy import, purify, reset, downloads and browser persistence.

project_actions_ui <- function(id) {
  ns <- NS(id)
  tagList(
    fluidRow(class = "vof-project-actions",
      column(2, actionButton(ns("restore_btn"), "Restore Project", class = "btn btn-info btn-block", icon = icon("history"))),
      column(2, actionButton(ns("legacy_btn"), "Import Legacy R", class = "btn btn-legacy btn-block", icon = icon("code"))),
      column(2, actionButton(ns("purify_btn"), "Purify Project", class = "btn btn-warning btn-block", icon = icon("filter"))),
      column(2, metadata_download_ui(ns("meta_dl"), label = "Metadata CSV", class = "btn btn-primary custom-download-btn btn-block")),
      column(2, downloadButton(ns("download_code"), "Project Code (.R)", class = "btn btn-primary custom-download-btn btn-block")),
      column(2, actionButton(ns("reset_btn"), "Reset All", class = "btn btn-danger btn-block", icon = icon("trash")))
    ),
    uiOutput(ns("history_status"))
  )
}

project_actions_server <- function(id, upload, history, media) {
  moduleServer(id, function(input, output, session) {
    metadata_download_server("meta_dl", history, upload)
    # Leaving the page with VOFs not downloaded: the browser asks first.
    observe(session$sendCustomMessage("vofmaker-unsaved", list(n = history$n_unsaved())))
    ns <- session$ns

    need_analytical <- function() {
      if (is.null(tryCatch(upload$data(), error = function(e) NULL))) {
        app_notify("Upload the Analytical first.", type = "warning"); return(FALSE)
      }
      TRUE
    }

    output$history_status <- renderUI({
      n <- history$n_rows()
      if (n == 0) return(NULL)
      div(class = "history-box", icon("database"),
          sprintf("%d rows of metadata stored (%d VOFs).", n, history$n_vofs()))
    })

    # --- Browser persistence (one entry per project) --------------------------
    browser_ready <- reactiveVal(FALSE)

    # Another Analytical (another project): the app starts over with it. The
    # metadata of the previous project is already saved in this browser under
    # its own key, so nothing is lost; the new project's saved metadata loads.
    current_key <- NULL
    observeEvent(upload$project_key(), {
      key <- upload$project_key()
      browser_ready(FALSE)              # first: nothing is saved under the new key while resetting
      if (!is.null(current_key) && !identical(key, current_key)) {
        history$clear()
        media$reset()
        app_notify("New Analytical loaded: the app started over for this project. The metadata of the previous project stays saved in this browser.",
                   type = "message", duration = 8)
      }
      current_key <<- key
      session$sendCustomMessage("vofmaker-load", list(key = key, input = ns("browser_history")))
    })

    observeEvent(input$browser_history, {
      msg <- input$browser_history
      if (!identical(msg$key, upload$project_key())) return()
      if (is_valid_value(msg$data) && history$n_rows() == 0) {
        restored <- tryCatch(metadata_from_json(msg$data), error = function(e) NULL)
        if (!is.null(restored) && nrow(restored) > 0) {
          history$replace(restored, saved_already = TRUE)   # it was saved in this browser
          app_notify(sprintf("Restored %d metadata rows saved in this browser for this project.", nrow(restored)),
                           type = "message", duration = 6)
        }
      }
      browser_ready(TRUE)
    })

    observeEvent(history$data(), {
      req(browser_ready())
      data <- if (history$n_rows() > 0) as.character(metadata_to_json(history$data())) else NULL
      session$sendCustomMessage("vofmaker-save", list(key = upload$project_key(), data = data))
    }, ignoreInit = TRUE)

    # --- Restore from generated code -------------------------------------------
    observeEvent(input$restore_btn, {
      if (!need_analytical()) return()
      showModal(modalDialog(
        title = "Restore from VOF Code", size = "l",
        p("Paste code generated by the VOF Maker. Every VOF is added to the history and the last one is loaded into the Variable Builder."),
        textAreaInput(ns("restore_code"), "Paste Code Here", rows = 15, width = "100%",
                      placeholder = "#### Title ####\nData[...] <- ..."),
        footer = tagList(modalButton("Cancel"), actionButton(ns("restore_confirm"), "Process & Restore", class = "btn btn-success"))
      ))
    })

    observeEvent(input$restore_confirm, {
      req(input$restore_code)
      vofs <- parse_vof_code(input$restore_code)
      if (length(vofs) == 0) { app_notify("No valid VOFs found.", type = "error"); return() }
      removeModal()
      history$upsert(parsed_vofs_to_metadata(vofs, upload$cs_dims()))

      roots <- vofs %>% map(~ map_chr(.x$components, "analytical_var")) %>% unlist() %>% unique()
      unknown <- setdiff(roots, upload$mff_vars())
      if (length(unknown) > 0)
        notify_messages(str_c("These variables are not MFF variables of the current Analytical: ", str_c(unknown, collapse = "; ")))

      # Last VOF of the code; with twins, the first VOF that shares its base name.
      last_base <- vof_base_name(names(vofs)[length(vofs)])
      last <- detect(names(vofs), ~ vof_base_name(.x) == last_base)
      media$load_vof(vofs[[last]]$components, vofs[[last]]$backcasting, name = last)
      app_notify(sprintf("Restored %d VOFs. Loaded '%s' into the builder.", length(vofs), last),
                       type = "message", duration = 8)
    })

    # --- Legacy import ---------------------------------------------------------
    observeEvent(input$legacy_btn, {
      if (!need_analytical()) return()
      showModal(modalDialog(
        title = "Import Legacy R Code", size = "l",
        p("Paste hand-written VOF code. Nested VOFs are resolved down to MFF variables, combining their period and cross-sectional filters."),
        p(tags$small("Supported: assignments to Data columns (Data$x, Data[['x']], Data[rows, 'x']), period filters (Period >= as.Date(...)) and CS filters (%in%, ==, startsWith, endsWith, grepl), included or negated with !(...).")),
        textAreaInput(ns("legacy_code"), "Paste R Code Here", rows = 15, width = "100%",
                      placeholder = "Data[, 'VOF'] <- rowSums(...)"),
        footer = tagList(modalButton("Cancel"), actionButton(ns("legacy_confirm"), "Process Legacy Code", class = "btn btn-success"))
      ))
    })

    observeEvent(input$legacy_confirm, {
      req(input$legacy_code)
      res <- parse_legacy_r_code(input$legacy_code, upload$mff_vars(), upload$cs_dims())
      if (nrow(res$metadata) == 0) {
        app_notify("No VOF definitions resolving to MFF variables were found.", type = "error"); return()
      }
      removeModal()
      history$upsert(res$metadata)
      app_notify(sprintf("Extracted %d metadata rows (%d VOFs) from the legacy code.",
                               nrow(res$metadata), length(unique(res$metadata$MainModelVariableName))),
                       type = "message", duration = 8)
      notify_messages(c(
        if (res$skipped_lines > 0) sprintf("%d lines could not be parsed and were skipped.", res$skipped_lines),
        if (res$negated_filters) "Some negated period filters were ignored; check those VOFs."
      ))
    })

    # --- Purify ----------------------------------------------------------------
    observeEvent(input$purify_btn, {
      if (!need_analytical()) return()
      if (!isTRUE(upload$has_details())) { app_notify("Upload the Model Details file first.", type = "warning"); return() }
      details <- upload$details(); req(details)
      if (history$n_rows() == 0) { app_notify("No metadata to purify.", type = "warning"); return() }

      res <- purify_metadata(history$data(), details, upload$cs_dims())
      history$replace(res$metadata)
      msg <- sprintf("Purified project: %d -> %d metadata rows.", res$rows_before, res$rows_after)
      if (length(res$missing) == 0) { app_notify(msg, type = "message", duration = 8); return() }

      shown <- if (length(res$missing) > 15) c(res$missing[1:15], paste("... and", length(res$missing) - 15, "more")) else res$missing
      showModal(modalDialog(
        title = tagList(icon("exclamation-triangle", class = "text-warning"), " Warning: Missing VOFs"),
        p(msg),
        p(tags$b("Based on your Model Details, these expected VOFs were NOT found in the VOF Metadata:")),
        tags$div(class = "vof-scroll-list", tags$ul(map(shown, tags$li))),
        p("Purification finished with the matching variables. Check whether the missing VOFs need to be built or imported."),
        easyClose = FALSE, footer = modalButton("I Understand & Continue")
      ))
    })

    # --- Reset -----------------------------------------------------------------
    observeEvent(input$reset_btn, {
      showModal(modalDialog(title = "Reset Project", "Delete all history (also the copy saved in this browser)?",
                            footer = tagList(modalButton("Cancel"),
                                             actionButton(ns("reset_confirm"), "Yes, Delete", class = "btn btn-danger"))))
    })

    observeEvent(input$reset_confirm, {
      removeModal()
      media$reset()
      history$clear()
      app_notify("Project reset.", type = "message")
    })

    # --- Downloads ---------------------------------------------------------------
    output$download_code <- downloadHandler(
      filename = function() str_c(format(Sys.time(), "%y%m%d%H%M%S"), " - VOF Code.R"),
      content = function(file) {
        dims <- tryCatch(upload$cs_dims(), error = function(e) intersect(MFF_DIMS, names(history$data())))
        write_lines(project_code_from_metadata(history$data(), dims), file)
      }
    )
  })
}
